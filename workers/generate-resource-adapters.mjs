#!/usr/bin/env node
// Package-contained adapters for the existing Relay target-resource contract.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export const resourceOwners = Object.freeze(['account', 'password']);
const entry = 'export function create(database, scope, configuration) {';
const wrapper = `
// Resource selection is separate from the original private facility payload.
export function create(database, scope, configuration, ...argumentsAfterConfiguration) {
  if (!configuration || typeof configuration !== 'object' || Array.isArray(configuration) ||
      !Object.hasOwn(configuration, 'implementation') ||
      configuration.implementation !== 'relay.auth-d1') {
    throw new Error('incompatible_target_resource');
  }
  const {implementation: selected, ...facilityConfiguration} = configuration;
  return createFacility(database, scope, facilityConfiguration, ...argumentsAfterConfiguration);
}
`;

export function generatedResourceAdapter(owner) {
  if (!resourceOwners.includes(owner)) throw new Error('Unsupported resource adapter owner');
  const source = readFileSync(new URL(`../crates/lenso-auth-${owner}-plugin/src/host_facilities/state.mjs`, import.meta.url), 'utf8');
  if (source.split(entry).length !== 2) throw new Error('Expected one canonical Auth facility factory');
  return '// @generated by node workers/generate-resource-adapters.mjs; DO NOT EDIT.\n'
    + '// Source: this package\'s src/host_facilities/state.mjs. No runtime imports.\n'
    + source.replace(entry, 'function createFacility(database, scope, configuration) {') + wrapper;
}

export function generateResourceAdapters({check = false} = {}) {
  const drift = [];
  for (const owner of resourceOwners) {
    const expected = generatedResourceAdapter(owner);
    const path = new URL(`../crates/lenso-auth-${owner}-plugin/src/host_facilities/state-resource.mjs`, import.meta.url);
    let actual;
    try { actual = readFileSync(path, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual === expected) continue;
    if (check) drift.push(owner);
    else writeFileSync(path, expected);
  }
  if (drift.length) throw new Error(`Generated Auth resource adapter drift: ${drift.join(', ')}. Run node workers/generate-resource-adapters.mjs`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node workers/generate-resource-adapters.mjs [--check]');
  generateResourceAdapters({check: process.argv.includes('--check')});
}
